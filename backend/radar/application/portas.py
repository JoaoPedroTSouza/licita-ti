"""Portas da aplicação: contratos que a infraestrutura implementa."""
from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal
from typing import Protocol, Self

from radar.domain.contato import Contato
from radar.domain.lembrete import Lembrete
from radar.domain.oportunidade import (
    Classificacao, Oportunidade, OportunidadeBruta, StatusOportunidade,
)
from radar.domain.perfil import Ajustes, Perfil
from radar.domain.processo import Processo


class ClassificacaoIndisponivel(Exception):
    """O classificador não conseguiu responder agora; tentar de novo depois."""


@dataclass(frozen=True)
class DescarteRecente:
    titulo: str
    motivo: str


@dataclass
class ExecucaoFonte:
    fonte: str
    iniciada_em: datetime
    finalizada_em: datetime
    recebidas: int
    novas: int
    erro: str | None


class Relogio(Protocol):
    def agora(self) -> datetime: ...


class FonteDeOportunidades(Protocol):
    nome: str

    def buscar(self, desde: date) -> list[OportunidadeBruta]: ...


class Classificador(Protocol):
    def classificar(
        self, bruta: OportunidadeBruta, perfil: Perfil, descartes: list[DescarteRecente]
    ) -> Classificacao: ...


class FonteDeCotacoes(Protocol):
    def cotacao(self, moeda: str, ate: date) -> tuple[date, Decimal] | None: ...


class Notificador(Protocol):
    def enviar(self, titulo: str, corpo: str, url: str) -> int: ...


class RepositorioOportunidades(Protocol):
    def adicionar(self, op: Oportunidade) -> Oportunidade: ...
    def obter(self, id: int) -> Oportunidade | None: ...
    def salvar(self, op: Oportunidade) -> None: ...
    def existe_chave(self, chave: str) -> bool: ...
    def pendentes(self, limite: int) -> list[Oportunidade]: ...
    def contar_pendentes(self) -> int: ...
    def listar(
        self, status: StatusOportunidade, limite: int | None = None
    ) -> list[Oportunidade]: ...
    def contar_novas_desde(self, desde: datetime) -> int: ...
    def descartes_recentes(self, limite: int = 20) -> list[DescarteRecente]: ...


class RepositorioProcessos(Protocol):
    def adicionar(self, processo: Processo) -> Processo: ...
    def obter(self, id: int) -> Processo | None: ...
    def salvar(self, processo: Processo) -> None: ...
    def listar(self) -> list[Processo]: ...


class RepositorioLembretes(Protocol):
    def adicionar(self, lembrete: Lembrete) -> Lembrete: ...
    def obter(self, id: int) -> Lembrete | None: ...
    def salvar(self, lembrete: Lembrete) -> None: ...
    def remover(self, id: int) -> None: ...
    def nao_concluidos(self) -> list[Lembrete]: ...
    def do_processo(self, processo_id: int) -> list[Lembrete]: ...


class RepositorioContatos(Protocol):
    def adicionar(self, contato: Contato) -> Contato: ...
    def obter(self, id: int) -> Contato | None: ...
    def salvar(self, contato: Contato) -> None: ...
    def listar(self) -> list[Contato]: ...


class RepositorioConfiguracoes(Protocol):
    def perfil(self) -> Perfil: ...
    def salvar_perfil(self, perfil: Perfil) -> None: ...
    def ajustes(self) -> Ajustes: ...
    def salvar_ajustes(self, ajustes: Ajustes) -> None: ...
    def obter_estado(self, chave: str) -> str | None: ...
    def salvar_estado(self, chave: str, valor: str) -> None: ...


class RepositorioExecucoes(Protocol):
    def registrar(self, execucao: ExecucaoFonte) -> None: ...
    def ultimas_por_fonte(self) -> list[ExecucaoFonte]: ...


class RepositorioCotacoes(Protocol):
    def salvar(self, moeda: str, dia: date, valor: Decimal) -> None: ...
    def mais_recentes(self) -> dict[str, Decimal]: ...


class UnidadeDeTrabalho(Protocol):
    oportunidades: RepositorioOportunidades
    processos: RepositorioProcessos
    lembretes: RepositorioLembretes
    contatos: RepositorioContatos
    configuracoes: RepositorioConfiguracoes
    execucoes: RepositorioExecucoes
    cotacoes: RepositorioCotacoes

    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def __enter__(self) -> Self: ...
    def __exit__(self, tipo, erro, traco) -> None: ...


class ArmazenamentoArquivos(Protocol):
    def salvar(self, nome: str, conteudo: bytes) -> str: ...
    def abrir(self, chave: str) -> bytes: ...
